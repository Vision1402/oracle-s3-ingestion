CREATE TABLE campaigns (
  campaign_id    NUMBER(8)          CONSTRAINT campaigns_pk PRIMARY KEY,
  campaign_name  VARCHAR2(100 CHAR) NOT NULL,
  channel        VARCHAR2(20)       NOT NULL,
  segment        VARCHAR2(30),
  launch_date    DATE,
  end_date       DATE,
  budget         NUMBER(12,2),
  status         VARCHAR2(15),
  last_updated   DATE DEFAULT SYSDATE
);

CREATE TABLE campaign_events (
  event_id     NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT campaign_events_pk PRIMARY KEY,
  campaign_id  NUMBER(8)    NOT NULL CONSTRAINT ce_campaign_fk REFERENCES campaigns (campaign_id),
  customer_id  NUMBER(10)   NOT NULL CONSTRAINT ce_customer_fk REFERENCES customers (customer_id),
  event_type   VARCHAR2(15) NOT NULL,
  event_ts     TIMESTAMP(6) NOT NULL,
  device       VARCHAR2(10),
  metadata     VARCHAR2(400)
);

CREATE INDEX campaign_events_ts_ix ON campaign_events (event_ts);
CREATE INDEX campaigns_last_updated_ix ON campaigns (last_updated);

PROMPT ===== 3. Generating campaigns and events (about 1 minute) =====
DECLARE
  TYPE t_str IS TABLE OF VARCHAR2(40);
  v_channel t_str := t_str('EMAIL','EMAIL','EMAIL','SMS','PUSH','DIRECT_MAIL');
  v_segment t_str := t_str('ALL_CUSTOMERS','LOYALTY_GOLD_PLUS','LAPSED_90D','NEW_CUSTOMERS','WHOLESALE');
  v_theme   t_str := t_str('Spring Sale','Summer Clearance','Back to School','Black Friday','Holiday Gifts',
                           'New Arrivals','Loyalty Bonus','Win Back','Weekend Flash','Outdoor Week');
  v_device  t_str := t_str('MOBILE','MOBILE','MOBILE','DESKTOP','TABLET');
  v_launch  DATE;
  v_ts      TIMESTAMP(6);
  v_cust    NUMBER;
  v_sends   PLS_INTEGER;
  v_dev     VARCHAR2(10);
  v_ch      VARCHAR2(20);
  v_name    VARCHAR2(100);
  v_seg     VARCHAR2(40);
BEGIN
  DBMS_RANDOM.SEED(7);
  FOR c IN 1 .. 40 LOOP
    v_launch := TRUNC(SYSDATE) - TRUNC(DBMS_RANDOM.VALUE(5, 730)) + DBMS_RANDOM.VALUE(0.3, 0.7);
    v_ch     := v_channel(TRUNC(DBMS_RANDOM.VALUE(1, v_channel.COUNT + 1)));
    -- Collection methods like .COUNT exist only in PL/SQL, not inside a SQL statement,
    -- so pick the values here first and pass plain variables to the INSERT.
    v_name   := v_theme(MOD(c - 1, v_theme.COUNT) + 1) || ' ' || TO_CHAR(v_launch, 'YYYY') || ' #' || c;
    v_seg    := v_segment(TRUNC(DBMS_RANDOM.VALUE(1, v_segment.COUNT + 1)));
    INSERT INTO campaigns (campaign_id, campaign_name, channel, segment, launch_date, end_date,
                           budget, status, last_updated)
    VALUES (c,
            v_name,
            v_ch,
            v_seg,
            v_launch,
            v_launch + 14,
            ROUND(DBMS_RANDOM.VALUE(2000, 60000), 2),
            CASE WHEN v_launch + 14 < SYSDATE THEN 'COMPLETED' ELSE 'ACTIVE' END,
            v_launch);

    v_sends := TRUNC(DBMS_RANDOM.VALUE(400, 1200));
    FOR s IN 1 .. v_sends LOOP
      v_cust := TRUNC(DBMS_RANDOM.VALUE(1001, 3001));
      v_ts   := CAST(v_launch AS TIMESTAMP) + NUMTODSINTERVAL(DBMS_RANDOM.VALUE(0, 3600), 'SECOND');
      v_dev  := v_device(TRUNC(DBMS_RANDOM.VALUE(1, v_device.COUNT + 1)));

      INSERT INTO campaign_events (campaign_id, customer_id, event_type, event_ts, device, metadata)
      VALUES (c, v_cust, 'SENT', v_ts, NULL, NULL);

      IF DBMS_RANDOM.VALUE < 0.95 THEN
        v_ts := v_ts + NUMTODSINTERVAL(DBMS_RANDOM.VALUE(5, 120), 'SECOND');
        INSERT INTO campaign_events (campaign_id, customer_id, event_type, event_ts, device, metadata)
        VALUES (c, v_cust, 'DELIVERED', v_ts, NULL, NULL);

        IF DBMS_RANDOM.VALUE < 0.35 THEN
          v_ts := v_ts + NUMTODSINTERVAL(DBMS_RANDOM.VALUE(60, 172800), 'SECOND');
          INSERT INTO campaign_events (campaign_id, customer_id, event_type, event_ts, device, metadata)
          VALUES (c, v_cust, 'OPENED', v_ts, v_dev, NULL);

          IF DBMS_RANDOM.VALUE < 0.20 THEN
            v_ts := v_ts + NUMTODSINTERVAL(DBMS_RANDOM.VALUE(5, 600), 'SECOND');
            INSERT INTO campaign_events (campaign_id, customer_id, event_type, event_ts, device, metadata)
            VALUES (c, v_cust, 'CLICKED', v_ts, v_dev,
                    '{"url":"/promo/' || c || '","utm_source":"' || LOWER(v_ch) || '","utm_campaign":"cmp' || c || '"}');

            IF DBMS_RANDOM.VALUE < 0.10 THEN
              v_ts := v_ts + NUMTODSINTERVAL(DBMS_RANDOM.VALUE(60, 7200), 'SECOND');
              INSERT INTO campaign_events (campaign_id, customer_id, event_type, event_ts, device, metadata)
              VALUES (c, v_cust, 'CONVERTED', v_ts, v_dev,
                      '{"order_value":' || TO_CHAR(ROUND(DBMS_RANDOM.VALUE(20, 400), 2), 'FM99990.00') || '}');
            END IF;
          END IF;
        END IF;
        IF DBMS_RANDOM.VALUE < 0.01 THEN
          INSERT INTO campaign_events (campaign_id, customer_id, event_type, event_ts, device, metadata)
          VALUES (c, v_cust, 'UNSUBSCRIBED', v_ts + NUMTODSINTERVAL(30, 'SECOND'), v_dev, NULL);
        END IF;
      END IF;
    END LOOP;
    COMMIT;
  END LOOP;
END;
