DECLARE
  TYPE t_str IS TABLE OF VARCHAR2(60 CHAR);
  v_first  t_str;
  v_last   t_str;
  v_city   t_str := t_str('New York','Boston','Chicago','San Antonio','Atlanta','Seattle','Los Angeles','Denver');
  v_state  t_str := t_str('NY','MA','IL','TX','GA','WA','CA','CO');
  v_cat    t_str := t_str('Apparel','Footwear','Home','Electronics','Outdoors');
  v_adj    t_str := t_str('Classic','Premium','Eco');
  v_noun   t_str := t_str('Tee','Hoodie','Denim Jacket','Chino Pants','Rain Coat',
                          'Running Shoe','Leather Boot','Canvas Sneaker','Sandal','Hiking Boot',
                          'Ceramic Mug','Throw Blanket','Desk Lamp','Scented Candle','Wall Clock',
                          'Wireless Earbuds','Phone Charger','Bluetooth Speaker','Smart Watch','USB Hub',
                          'Water Bottle','Daypack','Camping Chair','Headlamp','Trekking Poles');
  TYPE t_num_map IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
  v_price_by_id  t_num_map;
  TYPE t_line  IS RECORD (prod NUMBER, qty NUMBER, price NUMBER, disc NUMBER);
  TYPE t_lines IS TABLE OF t_line INDEX BY PLS_INTEGER;
  v_lines_tab  t_lines;
  v_u1 VARCHAR2(20 CHAR); v_u2 VARCHAR2(20 CHAR); v_u3 VARCHAR2(20 CHAR); v_u4 VARCHAR2(20 CHAR);
  v_fn          VARCHAR2(50 CHAR);
  v_ln          VARCHAR2(50 CHAR);
  v_ci          PLS_INTEGER;
  n             PLS_INTEGER;
  v_created     DATE;
  v_order_date  DATE;
  v_oid         NUMBER;
  v_cust        NUMBER;
  v_emp         NUMBER;
  v_nlines      PLS_INTEGER;
  v_total       NUMBER;
  v_rnd         NUMBER;
  v_status      VARCHAR2(20);
  v_notes       VARCHAR2(32767);
  v_ship_city   VARCHAR2(60);
BEGIN
  DBMS_RANDOM.SEED(42);   -- same "random" data every time you run this

  -- Accented names built from Unicode code points, so this file stays plain ASCII
  SELECT UNISTR('Jos\00E9'), UNISTR('Zo\00EB'), UNISTR('M\00FCller'), UNISTR('Nguy\1EC5n')
    INTO v_u1, v_u2, v_u3, v_u4
    FROM dual;
  v_first := t_str('James','Maria','Wei','Aisha',v_u1,v_u2,'Liam','Olivia','Noah','Emma',
                   'Raj','Priya','Chen','Fatima','Lucas','Sofia','Mateo','Hannah','Omar','Yuki');
  v_last  := t_str('Smith','Garcia','O''Brien',v_u3,v_u4,'Patel','Kim','Johnson','Brown','Rossi',
                   'Kowalski','Dubois','Tanaka','Silva','Anderson','Lee','Martin','Clark','Lopez','Wright');

  -- ---------- Employees (25): 1 CEO, 3 managers, 21 sales reps ----------
  FOR i IN 1 .. 25 LOOP
    v_fn := v_first(TRUNC(DBMS_RANDOM.VALUE(1, v_first.COUNT + 1)));
    v_ln := v_last(TRUNC(DBMS_RANDOM.VALUE(1, v_last.COUNT + 1)));
    INSERT INTO employees (first_name, last_name, email, job_title, national_id,
                           hire_date, salary, commission_pct, manager_id, last_updated)
    VALUES (v_fn, v_ln,
            LOWER(SUBSTR(v_fn, 1, 1) || REPLACE(v_ln, '''', '')) || i || '@northwind.example',
            CASE WHEN i = 1 THEN 'CEO' WHEN i <= 4 THEN 'Sales Manager' ELSE 'Sales Rep' END,
            LPAD(TRUNC(DBMS_RANDOM.VALUE(100, 1000)), 3, '0') || '-' ||
            LPAD(TRUNC(DBMS_RANDOM.VALUE(10, 100)), 2, '0')   || '-' ||
            LPAD(TRUNC(DBMS_RANDOM.VALUE(0, 10000)), 4, '0'),
            DATE '2009-01-01' + TRUNC(DBMS_RANDOM.VALUE(0, 5000)),
            CASE WHEN i = 1 THEN 245000
                 WHEN i <= 4 THEN ROUND(DBMS_RANDOM.VALUE(110000, 150000), 2)
                 ELSE ROUND(DBMS_RANDOM.VALUE(48000, 90000), 2) END,
            CASE WHEN i > 4 THEN ROUND(DBMS_RANDOM.VALUE(0.02, 0.12), 2) END,
            CASE WHEN i = 1 THEN NULL WHEN i <= 4 THEN 1 ELSE 2 + MOD(i, 3) END,
            DATE '2024-01-01' + DBMS_RANDOM.VALUE(0, 300));
  END LOOP;

  -- ---------- Products (60) ----------
  FOR i IN 1 .. 60 LOOP
    n := MOD(i - 1, 25) + 1;
    INSERT INTO products (product_name, category, unit_price, discontinued, last_updated)
    VALUES (v_adj(TRUNC((i - 1) / 25) + 1) || ' ' || v_noun(n),
            v_cat(TRUNC((n - 1) / 5) + 1),
            ROUND(DBMS_RANDOM.VALUE(5, 300), 2),
            CASE WHEN DBMS_RANDOM.VALUE < 0.08 THEN 'Y' ELSE 'N' END,
            DATE '2023-06-01' + DBMS_RANDOM.VALUE(0, 400));
  END LOOP;
  FOR r IN (SELECT product_id, unit_price FROM products) LOOP
    v_price_by_id(r.product_id) := r.unit_price;
  END LOOP;

  -- ---------- Customers (2,000) ----------
  FOR i IN 1 .. 2000 LOOP
    v_ci := TRUNC(DBMS_RANDOM.VALUE(1, v_city.COUNT + 1));
    v_fn := v_first(TRUNC(DBMS_RANDOM.VALUE(1, v_first.COUNT + 1)));
    v_ln := v_last(TRUNC(DBMS_RANDOM.VALUE(1, v_last.COUNT + 1)));
    IF MOD(i, 400) = 0 THEN
      v_created := DATE '1900-01-01';     -- legacy "unknown date" placeholder
    ELSE
      v_created := DATE '2012-01-01' + DBMS_RANDOM.VALUE(0, SYSDATE - DATE '2012-01-01');
    END IF;
    INSERT INTO customers (first_name, last_name, email, phone, city, state,
                           customer_type, is_active, created_date, last_updated)
    VALUES (v_fn, v_ln,
            CASE WHEN MOD(i, 50) = 0 THEN NULL
                 ELSE LOWER(REPLACE(v_fn || '.' || v_ln, '''', '')) || i || '@example.com' END,
            CASE WHEN MOD(i, 10) = 0 THEN ''    -- Oracle stores '' as NULL
                 ELSE '555-' || LPAD(TRUNC(DBMS_RANDOM.VALUE(0, 10000)), 4, '0') END,
            v_city(v_ci), v_state(v_ci),
            CASE WHEN DBMS_RANDOM.VALUE < 0.15 THEN 'WHOLESALE' ELSE 'RETAIL' END,
            CASE WHEN DBMS_RANDOM.VALUE < 0.05 THEN 'N' ELSE 'Y' END,
            v_created,
            LEAST(SYSDATE, GREATEST(v_created, DATE '2012-01-01') + DBMS_RANDOM.VALUE(0, 400)));
  END LOOP;
  COMMIT;

  -- ---------- Orders (20,000) + order lines (~50,000) ----------
  FOR i IN 1 .. 20000 LOOP
    v_oid        := orders_seq.NEXTVAL;
    v_order_date := DATE '2019-01-01' + DBMS_RANDOM.VALUE(0, (SYSDATE - 1) - DATE '2019-01-01');
    v_cust       := TRUNC(DBMS_RANDOM.VALUE(1001, 3001));
    v_emp        := TRUNC(DBMS_RANDOM.VALUE(5, 26));
    v_nlines     := TRUNC(DBMS_RANDOM.VALUE(1, 5));
    v_total      := 0;
    v_lines_tab.DELETE;

    FOR l IN 1 .. v_nlines LOOP
      v_lines_tab(l).prod  := TRUNC(DBMS_RANDOM.VALUE(1, 61));
      v_lines_tab(l).qty   := TRUNC(DBMS_RANDOM.VALUE(1, 6));
      v_lines_tab(l).price := v_price_by_id(v_lines_tab(l).prod);
      IF DBMS_RANDOM.VALUE < 0.3 THEN
        v_lines_tab(l).disc := ROUND(DBMS_RANDOM.VALUE(0.05, 0.25), 3);
      ELSE
        v_lines_tab(l).disc := 0;
      END IF;
      -- unrounded on purpose: order_total ends up with up to 5 decimal places
      v_total := v_total + v_lines_tab(l).qty * v_lines_tab(l).price * (1 - v_lines_tab(l).disc);
    END LOOP;

    v_rnd := DBMS_RANDOM.VALUE;
    IF    v_order_date > SYSDATE - 3  THEN v_status := 'PROCESSING';
    ELSIF v_order_date > SYSDATE - 10 THEN v_status := 'SHIPPED';
    ELSIF v_rnd < 0.05                THEN v_status := 'CANCELLED';
    ELSIF v_rnd < 0.09                THEN v_status := 'RETURNED';
    ELSE                                   v_status := 'DELIVERED';
    END IF;

    v_notes := NULL;
    IF MOD(i, 25) = 0 THEN
      v_notes := 'Customer asked for gift wrap, "fragile" items.' || CHR(10) ||
                 'Deliver after 5pm, ring twice.';
    ELSIF MOD(i, 997) = 0 THEN
      v_notes := RPAD('Legacy note carried over from the 2009 system. ', 6000,
                      'Legacy note carried over from the 2009 system. ');
    END IF;

    SELECT city INTO v_ship_city FROM customers WHERE customer_id = v_cust;
    IF DBMS_RANDOM.VALUE < 0.1 THEN
      v_ship_city := v_city(TRUNC(DBMS_RANDOM.VALUE(1, v_city.COUNT + 1)));
    END IF;

    INSERT INTO orders (order_id, customer_id, employee_id, order_date, status,
                        ship_city, notes, order_total, last_updated)
    VALUES (v_oid, v_cust, v_emp, v_order_date, v_status,
            v_ship_city, v_notes, v_total,
            LEAST(SYSDATE, v_order_date + DBMS_RANDOM.VALUE(0, 20)));

    FOR l IN 1 .. v_nlines LOOP
      INSERT INTO order_lines (order_id, line_no, product_id, quantity, unit_price, discount, last_updated)
      VALUES (v_oid, l, v_lines_tab(l).prod, v_lines_tab(l).qty,
              v_lines_tab(l).price, v_lines_tab(l).disc, v_order_date);
    END LOOP;

    IF MOD(i, 5000) = 0 THEN
      COMMIT;
      DBMS_OUTPUT.PUT_LINE('  ... ' || i || ' orders generated');
    END IF;
  END LOOP;
  COMMIT;
END;
