PROMPT ===== 4. Procedure that simulates a new day of activity =====
CREATE OR REPLACE PROCEDURE simulate_new_activity (p_events IN NUMBER DEFAULT 500) AS
  -- Creates p_events new campaign events "now", edits 20 customers and 1 campaign.
  -- Use it to test incremental loads: run it, then re-run the ingestion.
  v_camp NUMBER;
  v_type VARCHAR2(15);
  v_rnd  NUMBER;
BEGIN
  FOR i IN 1 .. p_events LOOP
    v_camp := TRUNC(DBMS_RANDOM.VALUE(1, 41));
    v_rnd  := DBMS_RANDOM.VALUE;
    IF    v_rnd < 0.50 THEN v_type := 'OPENED';
    ELSIF v_rnd < 0.85 THEN v_type := 'CLICKED';
    ELSE                    v_type := 'CONVERTED';
    END IF;
    INSERT INTO campaign_events (campaign_id, customer_id, event_type, event_ts, device, metadata)
    VALUES (v_camp, TRUNC(DBMS_RANDOM.VALUE(1001, 3001)), v_type,
            SYSTIMESTAMP - NUMTODSINTERVAL(DBMS_RANDOM.VALUE(240, 300), 'SECOND'),   -- 4-5 minutes ago
            'MOBILE', NULL);
  END LOOP;

  UPDATE customers
     SET phone = '555-' || LPAD(TRUNC(DBMS_RANDOM.VALUE(0, 10000)), 4, '0')
   WHERE customer_id IN (SELECT customer_id FROM
                           (SELECT customer_id FROM customers ORDER BY DBMS_RANDOM.VALUE)
                         WHERE ROWNUM <= 20);

  v_camp := TRUNC(DBMS_RANDOM.VALUE(1, 41));   -- pick ONE campaign (a random value inside WHERE would change per row)
  UPDATE campaigns
     SET budget = budget + 1000, last_updated = SYSDATE
   WHERE campaign_id = v_camp;
  COMMIT;
  DBMS_OUTPUT.PUT_LINE(p_events || ' events added, 20 customers and 1 campaign updated at '
                       || TO_CHAR(SYSTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'));
END simulate_new_activity;
