-- Run as NORTHWIND, connected to FREEPDB1. Safe to re-run (it drops and rebuilds).
--
-- Contains, on purpose, the habits of a real 15-year-old Oracle system:
--   * DATE columns that secretly hold a time of day
--   * NUMBER columns with no precision (order_total, discount)
--   * Sequences + triggers for IDs (pre-12c style) and "last_updated" stamping
--   * Y/N CHAR(1) flags instead of booleans
--   * '' (empty string) silently stored as NULL
--   * A CLOB column with commas, quotes and line breaks
--   * Placeholder dates (1900-01-01), accented names, apostrophes
--   * PL/SQL business logic + a DBMS_SCHEDULER nightly job
-- =====================================================================
