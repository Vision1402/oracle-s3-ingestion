PROMPT ===== 7. Business logic: monthly sales summary (PL/SQL) =====
CREATE OR REPLACE PROCEDURE refresh_sales_summary AS
  v_start  DATE := SYSDATE;
  v_rows   NUMBER;
  v_err    VARCHAR2(4000);
BEGIN
  DELETE FROM monthly_sales_summary;
  INSERT INTO monthly_sales_summary (sales_month, customer_type, order_count, gross_revenue, refreshed_at)
  SELECT TRUNC(o.order_date, 'MM'),
         c.customer_type,
         COUNT(*),
         SUM(o.order_total),
         SYSDATE
  FROM orders o
  JOIN customers c ON c.customer_id = o.customer_id
  WHERE o.status NOT IN ('CANCELLED', 'RETURNED')
  GROUP BY TRUNC(o.order_date, 'MM'), c.customer_type;
  v_rows := SQL%ROWCOUNT;

  INSERT INTO batch_log (job_name, started_at, finished_at, rows_affected, status)
  VALUES ('REFRESH_SALES_SUMMARY', v_start, SYSDATE, v_rows, 'SUCCESS');
  COMMIT;
EXCEPTION
  WHEN OTHERS THEN
    v_err := SUBSTR(SQLERRM, 1, 4000);
    ROLLBACK;
    INSERT INTO batch_log (job_name, started_at, finished_at, rows_affected, status, error_message)
    VALUES ('REFRESH_SALES_SUMMARY', v_start, SYSDATE, 0, 'FAILED', v_err);
    COMMIT;
    RAISE;
END refresh_sales_summary;
