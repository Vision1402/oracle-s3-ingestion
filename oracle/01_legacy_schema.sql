PROMPT ===== 6. Business logic: loyalty tiers (PL/SQL) =====
CREATE OR REPLACE PROCEDURE calc_loyalty_tiers AS
  -- Rule (from the 2011 marketing spec): spend in the last 12 months,
  -- excluding cancelled and returned orders, decides the tier.
  v_start  DATE := SYSDATE;
  v_rows   NUMBER;
  v_err    VARCHAR2(4000);
BEGIN
  MERGE INTO customers c
  USING (
    SELECT cu.customer_id,
           CASE
             WHEN NVL(SUM(o.order_total), 0) >= 5000 THEN 'PLATINUM'
             WHEN NVL(SUM(o.order_total), 0) >= 2500 THEN 'GOLD'
             WHEN NVL(SUM(o.order_total), 0) >= 1000 THEN 'SILVER'
             ELSE 'BRONZE'
           END AS new_tier
    FROM customers cu
    LEFT JOIN orders o
           ON o.customer_id = cu.customer_id
          AND o.status NOT IN ('CANCELLED', 'RETURNED')
          AND o.order_date >= ADD_MONTHS(TRUNC(SYSDATE), -12)
    GROUP BY cu.customer_id
  ) s
  ON (c.customer_id = s.customer_id)
  WHEN MATCHED THEN
    UPDATE SET c.loyalty_tier = s.new_tier
    WHERE DECODE(c.loyalty_tier, s.new_tier, 0, 1) = 1;   -- NULL-safe "has it changed?"
  v_rows := SQL%ROWCOUNT;

  INSERT INTO batch_log (job_name, started_at, finished_at, rows_affected, status)
  VALUES ('CALC_LOYALTY_TIERS', v_start, SYSDATE, v_rows, 'SUCCESS');
  COMMIT;
EXCEPTION
  WHEN OTHERS THEN
    v_err := SUBSTR(SQLERRM, 1, 4000);
    ROLLBACK;
    INSERT INTO batch_log (job_name, started_at, finished_at, rows_affected, status, error_message)
    VALUES ('CALC_LOYALTY_TIERS', v_start, SYSDATE, 0, 'FAILED', v_err);
    COMMIT;
    RAISE;
END calc_loyalty_tiers;
